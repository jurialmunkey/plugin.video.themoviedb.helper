from threading import Event, Lock
from traceback import format_exc
from jurialmunkey.ftools import cached_property
from tmdbhelper.lib.addon.logger import kodi_log
from tmdbhelper.lib.addon.thread import SafeThread
from tmdbhelper.lib.monitor.images import ImageFunctions


class ImageManipulationJob:
    """ One image manipulation of one item for the images monitor

    The job is generated by its worker and its properties are applied with the setter
    provided by the monitor. Jobs replaced while waiting, or cancelled before completion, are not applied.
    """

    def __init__(self, method, source, cancel_id, set_properties):
        self.method = method
        self.source = source
        self.cancel_id = cancel_id
        self.set_properties = set_properties
        self.generated = False
        self.applied = False
        self.done = Event()

    @cached_property
    def image_functions(self):
        return self.get_image_functions()

    def get_image_functions(self):
        return ImageFunctions(method=self.method, is_thread=False, artwork=self.source)

    @cached_property
    def output(self):
        return self.get_output()

    def get_output(self):
        return self.image_functions.func(self.source)

    @property
    def properties(self):
        return {
            f'{self.method}image': self.output,
            f'{self.method}image.original': self.source,
        }

    def generate(self):
        self.output
        self.generated = True

    def apply(self):
        self.set_properties(self.properties)
        self.applied = True

    def finish(self):
        self.done.set()


class ImageColorsJob(ImageManipulationJob):
    """ Colors are calculated by the worker and only set to their properties when the job is applied """

    @cached_property
    def colors(self):
        return self.get_colors()

    def get_colors(self):
        return self.image_functions.get_colors(self.source)

    def get_output(self):
        return self.colors[0] if self.colors else ''

    def apply(self):
        super().apply()
        if self.colors:
            self.image_functions.set_colors_properties(*self.colors)


class ImageManipulationWorker:
    """ Generates one job at a time and keeps one job waiting

    A newer job replaces the waiting job. When a job is generated, the worker starts the
    waiting job if there is one and otherwise applies the generated job. The worker thread
    only runs while there is work, so idle manipulations do not hold a thread.
    """

    apply_superseded = False  # Apply generated jobs even when a newer job is waiting

    def __init__(self, workers, method):
        self.workers = workers  # ImageManipulationWorkers
        self.method = method
        self.lock = Lock()
        self.queued = None
        self.running = False

    def submit(self, job):
        with self.lock:
            if self.running:
                self.replace_queued(job)
                return
            self.running = True
        thread = SafeThread(target=self.process, args=[job])
        thread.setName(f'Image {self.method} Thread')
        thread.start()

    def replace_queued(self, job=None):
        if self.queued is not None:
            self.queued.finish()
        self.queued = job

    def cancel(self):
        with self.lock:
            self.replace_queued()

    def process(self, job):
        while job is not None:
            self.generate(job)
            job = self.get_next_job(job)

    def generate(self, job):
        try:
            job.generate()
        except Exception:
            kodi_log(f'Image {self.method} failed for {job.source}:\n{format_exc()}', 1)

    def get_next_job(self, job):
        with self.lock:
            next_job, self.queued = self.queued, None
            self.running = next_job is not None
            if self.apply_superseded or not self.running:
                self.complete(job)
            else:
                job.finish()
            return next_job

    def complete(self, job):
        """ Apply generated job unless jobs have been cancelled since it was submitted """
        try:
            if job.generated and self.workers.is_current(job):
                job.apply()
        except Exception:
            kodi_log(f'Image {self.method} properties failed for {job.source}:\n{format_exc()}', 1)
        finally:
            job.finish()


class ImageStreamingWorker(ImageManipulationWorker):
    """ Applies every generated job before starting the waiting job, so scrolling shows each result """

    apply_superseded = True


class ImageManipulationWorkers:
    """ One worker per image manipulation, created when the manipulation is first requested """

    job_classes = {
        'colors': ImageColorsJob,
    }

    worker_classes = {
        'crop': ImageStreamingWorker,
    }

    def __init__(self):
        self.lock = Lock()
        self.workers = {}
        self.cancel_id = 0

    def get_worker(self, method):
        try:
            return self.workers[method]
        except KeyError:
            worker_class = self.worker_classes.get(method, ImageManipulationWorker)
            worker = self.workers[method] = worker_class(self, method)
            return worker

    def get_job(self, method, source, cancel_id, set_properties):
        job_class = self.job_classes.get(method, ImageManipulationJob)
        return job_class(method, source, cancel_id, set_properties)

    def submit(self, requests, set_properties):
        """ Submit a job for each manipulation request and return the jobs """
        with self.lock:
            jobs = [
                self.get_job(method, source, self.cancel_id, set_properties)
                for method, source in requests.items()
            ]
            for job in jobs:
                self.get_worker(job.method).submit(job)
        return jobs

    def is_current(self, job):
        return job.cancel_id == self.cancel_id

    def cancel(self):
        """ Stop jobs already submitted from being applied """
        with self.lock:
            self.cancel_id += 1
            workers = tuple(self.workers.values())
        for worker in workers:
            worker.cancel()
